const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('yl_lang') : ''
export const lang = ref(saved === 'en' ? 'en' : 'zh')
export const isEn = computed(() => lang.value === 'en')
const dict = { zh, en }

export function setLang(l) {
  lang.value = l === 'en' ? 'en' : 'zh'
  localStorage.setItem('yl_lang', lang.value)
  document.documentElement.lang = lang.value
}

export function t(key, vars) {
  let s = dict[lang.value][key] ?? dict.zh[key] ?? key
  if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k])
  return s
}

// 产品细分类别显示：优先翻译，未知值回退原文
export function subLabel(s) {
  if (!s) return s
  const key = 'subcat_' + s
  const tr = t(key)
  return tr === key ? s : tr
}

